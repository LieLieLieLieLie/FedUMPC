"""Fresh held-out MuJoCo evaluation after development-only adapter selection."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import r1_mujoco_final as evaluation
import run_six_algorithms as core


ROOT = Path(__file__).resolve().parent
TAG = "IoT-72582-2026|FedUMPC|R1-MuJoCo-refined-slack001|2026-11-05"


def _prior_seeds() -> set[int]:
    seeds = set(evaluation.EXCLUDED) | set(evaluation.SEEDS)
    for path in (
        ROOT / "outputs_r1_final" / "protocol.json",
        ROOT / "diagnostic_r1d_outputs" / "protocol.json",
    ):
        if path.exists():
            payload = json.loads(path.read_text(encoding="utf-8"))
            seeds.update(int(value) for value in payload.get("heldout_seeds", []))
    return seeds


def _protocol_payload() -> dict:
    return {
        "protocol": "Fresh MuJoCo evaluation after development-only structural selection",
        "seed_derivation_tag": TAG,
        "seed_derivation_sha256": hashlib.sha256(TAG.encode()).hexdigest(),
        "heldout_seeds": evaluation.SEEDS,
        "excluded_development_and_previous_seeds": sorted(evaluation.EXCLUDED),
        "predictor_training_seed": evaluation.TRAINING_SEED,
        "predictor_training_source": "one-step transitions generated by MuJoCo",
        "vehicle_masses_kg": core.VEHICLE_MASSES.tolist(),
        "methods": list(core.METHODS),
        "fedumpc_adaptive_margin_enabled": False,
        "fedumpc_direct_risk_cost_enabled": False,
        "fedumpc_trust_cap": core.FED_TRUST_CAP,
        "fedumpc_soft_obstacle_weight": core.FED_SOFT_WEIGHT,
        "fedumpc_near_cost_relative_tolerance": core.FED_COST_SLACK,
        "development_selection": {
            "scenes": 13,
            "selected_relative_tolerance": 0.001,
            "rule": "maximize endpoint first-place count, then minimize mean rank",
        },
        "source_sha256": {
            "run_six_algorithms.py": evaluation.sha256(ROOT / "run_six_algorithms.py"),
            "r1_mujoco_refined.py": evaluation.sha256(Path(__file__).resolve()),
        },
    }


def main() -> None:
    core.FED_COST_SLACK = 0.001
    evaluation.OUTPUT = ROOT / "outputs_r1_refined"
    evaluation.PROTOCOL_PATH = evaluation.OUTPUT / "protocol.json"
    evaluation.RAW_PATH = evaluation.OUTPUT / "mujoco_runs.csv"
    evaluation.SUMMARY_PATH = evaluation.OUTPUT / "mujoco_summary.csv"
    evaluation.TAG = TAG
    evaluation.EXCLUDED = _prior_seeds()
    evaluation.SEEDS = evaluation.derive_seeds(count=12)
    evaluation.protocol_payload = _protocol_payload
    evaluation.main()


if __name__ == "__main__":
    main()
