"""Independent MuJoCo evaluation of the nominal-guarded controller."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import r1_mujoco_final as runner


ROOT = Path(__file__).resolve().parent
runner.OUTPUT = ROOT / "outputs_r1_guarded"
runner.PROTOCOL_PATH = runner.OUTPUT / "protocol.json"
runner.RAW_PATH = runner.OUTPUT / "mujoco_runs.csv"
runner.SUMMARY_PATH = runner.OUTPUT / "mujoco_summary.csv"
runner.TAG = "IoT-72582-2026|FedUMPC|R1-MuJoCo-nominal-guard|2026-11-06"
runner.EXCLUDED = set(runner.EXCLUDED) | set(runner.SEEDS)
runner.TRAINING_SEED = 20261106
runner.SEEDS = runner.derive_seeds(count=12)


def protocol_payload() -> dict:
    core = runner.core
    return {
        "protocol": "Independent MuJoCo evaluation of nominal-guarded FedUMPC",
        "seed_derivation_tag": runner.TAG,
        "seed_derivation_sha256": hashlib.sha256(runner.TAG.encode()).hexdigest(),
        "heldout_seeds": runner.SEEDS,
        "excluded_development_and_previous_seeds": sorted(runner.EXCLUDED),
        "heldout_results_used_for_selection": False,
        "predictor_training_seed": runner.TRAINING_SEED,
        "predictor_training_source": "one-step transitions generated by MuJoCo",
        "vehicle_masses_kg": core.VEHICLE_MASSES.tolist(),
        "methods": list(core.METHODS),
        "fedumpc_adaptive_margin_enabled": False,
        "fedumpc_direct_uncertainty_cost_enabled": False,
        "fedumpc_trust_cap": core.FED_TRUST_CAP,
        "fedumpc_screen_horizon": core.FED_SCREEN_HORIZON,
        "fedumpc_nominal_cost_slack": core.FED_GUARD_NOMINAL_SLACK,
        "fedumpc_clearance_gain_m": core.FED_GUARD_CLEARANCE_GAIN,
        "source_sha256": {
            "run_six_algorithms.py": runner.sha256(ROOT / "run_six_algorithms.py"),
            "r1_mujoco_guarded.py": runner.sha256(Path(__file__).resolve()),
        },
    }


runner.protocol_payload = protocol_payload


if __name__ == "__main__":
    runner.main()
